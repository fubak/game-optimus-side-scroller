/**
 * 5×7 bitmap font.
 *
 * At a 480×270 internal resolution the browser's own text rendering is blurry and inconsistent, so
 * the HUD and menus paint glyphs as pixels instead. Each glyph is seven rows of five bits, MSB on
 * the left: `0b10001` is two pixels at the outer edges.
 */

export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

/** Unscaled pixel size of one bitmap pixel; both renderers key their metrics off this. */
export const FONT_SCALE = 1;

